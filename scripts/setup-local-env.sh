#!/usr/bin/env bash
# Generate .env.local for local development from the running local Supabase stack.
# Safe to re-run: it overwrites .env.local with fresh values each time.
#
# The Supabase anon/service-role keys printed by `supabase status` are the well-known
# local-development demo keys — they only work against the local stack and are not secrets.
# Stripe/Resend values are placeholders so the app boots and the catalog is browsable;
# override them with real test keys to exercise checkout/email locally.
set -euo pipefail

cd "$(dirname "$0")/.."

if ! pnpm supabase status >/dev/null 2>&1; then
  echo "Local Supabase is not running. Start it with: pnpm supabase start" >&2
  exit 1
fi

eval "$(pnpm supabase status -o env 2>/dev/null | grep -E '^(API_URL|ANON_KEY|SERVICE_ROLE_KEY)=')"

cat > .env.local <<EOF
# Auto-generated by scripts/setup-local-env.sh — do not commit (see .gitignore).
# Local Supabase (well-known local demo keys; not secrets).
NEXT_PUBLIC_SUPABASE_URL=${API_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}

# Stripe / Resend — dev placeholders. Replace with real test keys to exercise
# checkout + transactional email end-to-end.
STRIPE_SECRET_KEY=${STRIPE_SECRET_KEY:-sk_test_placeholder}
STRIPE_WEBHOOK_SECRET=${STRIPE_WEBHOOK_SECRET:-whsec_placeholder}
RESEND_API_KEY=${RESEND_API_KEY:-re_placeholder}
RESEND_FROM_EMAIL=${RESEND_FROM_EMAIL:-orders@example.com}

# Admin gate + checkout redirect base.
ADMIN_EMAILS=${ADMIN_EMAILS:-admin@example.com}
NEXT_PUBLIC_SITE_URL=${NEXT_PUBLIC_SITE_URL:-http://localhost:3000}
EOF

echo "Wrote .env.local (NEXT_PUBLIC_SUPABASE_URL=${API_URL})"
